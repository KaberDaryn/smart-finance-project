import sqlite3
from contextlib import contextmanager
from datetime import date, datetime, timezone
from threading import Lock

_schema_lock = Lock()
_initialized = set()


def marker(db):
    return '?' if isinstance(db, sqlite3.Connection) else '%s'


@contextmanager
def transaction(db):
    try:
        yield
        db.commit()
    except Exception:
        db.rollback()
        raise


def connect(database):
    postgres = str(database).startswith(('postgres://', 'postgresql://'))
    if postgres:
        import psycopg
        from psycopg.rows import dict_row
        db = psycopg.connect(database, row_factory=dict_row)
    else:
        db = sqlite3.connect(database, timeout=15)
        db.row_factory = sqlite3.Row
        db.execute('PRAGMA foreign_keys=ON')
    try:
        with _schema_lock:
            if str(database) not in _initialized:
                initialize(db, postgres)
                _initialized.add(str(database))
    except Exception:
        db.close()
        raise
    return db


def initialize(db, postgres):
    identity = 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if postgres else 'INTEGER PRIMARY KEY'
    with transaction(db):
        db.execute(f'''CREATE TABLE IF NOT EXISTS users (
            id {identity}, username TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL,
            salt TEXT NOT NULL, created_at TEXT NOT NULL)''')
        db.execute(f'''CREATE TABLE IF NOT EXISTS sessions (
            token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
            expires_at TEXT NOT NULL)''')
        db.execute(f'''CREATE TABLE IF NOT EXISTS transactions (
            id {identity}, kind TEXT NOT NULL CHECK(kind IN ('income','expense')),
            amount_minor BIGINT NOT NULL CHECK(amount_minor > 0), category TEXT NOT NULL,
            description TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
            user_id BIGINT REFERENCES users(id))''')
        if postgres:
            db.execute('ALTER TABLE transactions ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES users(id)')
        elif 'user_id' not in {row['name'] for row in db.execute('PRAGMA table_info(transactions)')}:
            db.execute('ALTER TABLE transactions ADD COLUMN user_id BIGINT REFERENCES users(id)')
        db.execute('CREATE INDEX IF NOT EXISTS transactions_owner ON transactions(user_id)')
        db.execute(f'''CREATE TABLE IF NOT EXISTS budgets (
            id {identity}, user_id BIGINT NOT NULL REFERENCES users(id), month TEXT NOT NULL,
            category TEXT NOT NULL, amount_minor BIGINT NOT NULL CHECK(amount_minor > 0),
            UNIQUE(user_id, month, category))''')
        db.execute(f'''CREATE TABLE IF NOT EXISTS goals (
            id {identity}, user_id BIGINT NOT NULL REFERENCES users(id), name TEXT NOT NULL,
            target_minor BIGINT NOT NULL CHECK(target_minor > 0), saved_minor BIGINT NOT NULL DEFAULT 0,
            CHECK(saved_minor >= 0 AND saved_minor <= target_minor))''')
        db.execute('''CREATE TABLE IF NOT EXISTS imports (
            user_id BIGINT NOT NULL REFERENCES users(id), content_hash TEXT NOT NULL,
            PRIMARY KEY(user_id, content_hash))''')


@contextmanager
def connection(database):
    db = connect(database)
    try:
        yield db
    finally:
        db.close()


def prepare(payload):
    if not isinstance(payload, dict):
        raise ValueError('Expected a JSON object')
    kind, amount = payload.get('kind'), payload.get('amount_minor')
    category, description = payload.get('category'), payload.get('description', '')
    occurred_on = payload.get('date')
    if occurred_on is not None:
        if not isinstance(occurred_on, str) or len(occurred_on) != 10:
            raise ValueError('date must use YYYY-MM-DD')
        try:
            parsed_date = date.fromisoformat(occurred_on)
        except ValueError as error:
            raise ValueError('date must be a valid calendar date') from error
        if parsed_date > datetime.now(timezone.utc).date():
            raise ValueError('date cannot be in the future')
        created_at = occurred_on + ' 00:00:00'
    else:
        created_at = datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S')
    if kind not in ('income', 'expense'):
        raise ValueError('kind must be income or expense')
    if type(amount) is not int or not 0 < amount <= 10**12:
        raise ValueError('amount_minor must be a positive integer up to 10^12')
    if not isinstance(category, str) or not category.strip() or len(category) > 100:
        raise ValueError('category must contain 1 to 100 characters')
    if not isinstance(description, str) or len(description) > 1000:
        raise ValueError('description must contain at most 1000 characters')
    return (kind, amount, category.strip(), description.strip(), created_at)


def insert(db, values, user_id):
    placeholders = ', '.join([marker(db)] * 6)
    row = db.execute(f'''INSERT INTO transactions(kind, amount_minor, category, description, created_at, user_id)
                        VALUES ({placeholders}) RETURNING *''', (*values, user_id)).fetchone()
    result = dict(row)
    result.pop('user_id', None)
    return result


def add(db, payload, user_id=None):
    values = prepare(payload)
    with transaction(db):
        return insert(db, values, user_id)


def transactions(db, user_id=None):
    where = 'user_id IS NULL' if user_id is None else f'user_id = {marker(db)}'
    params = () if user_id is None else (user_id,)
    rows = db.execute(f'SELECT * FROM transactions WHERE {where} ORDER BY SUBSTR(created_at, 1, 10) DESC, id DESC', params)
    results = []
    for row in rows:
        result = dict(row)
        result.pop('user_id', None)
        results.append(result)
    return results


def summary(db, user_id=None):
    totals = {'income': 0, 'expense': 0}
    where = 'user_id IS NULL' if user_id is None else f'user_id = {marker(db)}'
    for row in db.execute(f'SELECT kind, SUM(amount_minor) AS total FROM transactions WHERE {where} GROUP BY kind',
                          () if user_id is None else (user_id,)):
        totals[row['kind']] = int(row['total'])
    return {'currency': 'KZT', 'income_minor': totals['income'], 'expense_minor': totals['expense'],
            'balance_minor': totals['income'] - totals['expense']}
